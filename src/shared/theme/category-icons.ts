// Names the app used before icons were stored; kept so old defaults still render.
const LEGACY_ICON_ALIASES: Record<string, string> = { 'plus-circle': 'circle-plus' };

const ICONS_BY_NAME = new Map(CATEGORY_ICON_OPTIONS.map((option) => [option.name, option.Component]));

export function categoryIconComponent(name: string | null | undefined): LucideIcon {
  if (!name) return Circle;
  return ICONS_BY_NAME.get(LEGACY_ICON_ALIASES[name] ?? name) ?? Circle;
}
